# --- LLM usage notes ---------------------------------------------------------
#
# Design notes:
#
#  * The prompt is a versioned artifact.  USAGE_NOTE_PROMPT_VERSION is part of
#    the cache key, so bumping it after changing the prompt forces a clean
#    regeneration of every note.
#  * The cache key is (model, prompt_version, word, translation) - NOT the
#    example sentence, so tweaking an example doesn't regenerate every note.
#  * Generation is fail-per-entry: a single bad call appends to the failure
#    list rather than aborting the run.
#  * Ollama availability is checked ONCE, up front, with a clear error message
#    if the server isn't reachable - not once per entry.

USAGE_NOTE_PROMPT_VERSION = "1"

USAGE_NOTE_SYSTEM = (
    "You are a concise Russian-language tutor writing short usage notes for "
    "an English-speaking learner of Russian. You write plain prose in English, "
    "not bullet points, not markdown, not numbered lists. You are honest about "
    "uncertainty: if you are not confident about a grammatical or register "
    "claim, you omit it rather than guessing."
)

USAGE_NOTE_USER_TEMPLATE = (
    "Russian word: {word}\n"
    "Translation given: {translation}\n"
    "Example sentence (for disambiguation only): {example_ru}\n"
    "\n"
    "In 1 to 2 short sentences, describe how this Russian word is used in "
    "practice: its register (formal / neutral / colloquial), any common "
    "collocations, and at most ONE common point of confusion for English "
    "speakers (such as a false friend or a similarly-spelled word with a "
    "different meaning).\n"
    "\n"
    "Rules:\n"
    "- Do NOT repeat the translation verbatim.\n"
    "- Do NOT comment on the example sentence itself.\n"
    "- Do NOT add your own example sentences.\n"
    "- Do NOT use markdown, bullet points, or bold.\n"
    "- If you are not confident about a claim, omit it.\n"
    "- Maximum 2 sentences. Aim for 25-45 words total.\n"
)


def llm_cache_key_for(model: str, prompt_version: str, word: str, translation: str) -> str:
    raw = f"{model}|{prompt_version}|{word}|{translation}"
    return hashlib.sha1(raw.encode("utf-8")).hexdigest()[:16]


def check_ollama_available(host: str, model: str) -> None:
    """Fail fast with a clear message if Ollama isn't reachable / model missing."""
    url = f"{host.rstrip('/')}/api/tags"
    try:
        with urllib.request.urlopen(url, timeout=5) as response:
            payload = json.loads(response.read().decode("utf-8"))
    except urllib.error.URLError as exc:
        raise LLMError(
            f"Ollama is not reachable at {host}.\n"
            f"Start it with:  ollama serve\n"
            f"Underlying error: {exc}"
        ) from exc
    except Exception as exc:  # noqa: BLE001
        raise LLMError(f"Could not query Ollama at {host}: {exc}") from exc

    available = {m.get("name", "") for m in payload.get("models", [])}
    # Ollama reports names with an implicit ':latest' tag sometimes; accept either.
    if model not in available and f"{model}:latest" not in available:
        raise LLMError(
            f"Ollama is running at {host} but model '{model}' is not installed.\n"
            f"Pull it with:  ollama pull {model}\n"
            f"Installed models: {', '.join(sorted(available)) or '(none)'}"
        )


def _call_ollama(
    host: str, model: str, system: str, user: str,
    timeout: float, temperature: float, max_tokens: int,
) -> str:
    """Single blocking call to Ollama's /api/chat. Raises LLMError on failure."""
    url = f"{host.rstrip('/')}/api/chat"
    body = {
        "model": model,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
        "stream": False,
        "options": {
            "temperature": temperature,
            "num_predict": max_tokens,
        },
    }
    request = urllib.request.Request(
        url,
        data=json.dumps(body).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            payload = json.loads(response.read().decode("utf-8"))
    except urllib.error.URLError as exc:
        raise LLMError(f"Ollama request failed: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise LLMError(f"Ollama returned malformed JSON: {exc}") from exc

    content = (payload.get("message") or {}).get("content", "").strip()
    if not content:
        raise LLMError("Ollama returned an empty response.")
    return content


def _sanitize_usage_note(note: str) -> str:
    """Strip markdown/HTML the model may have produced anyway, collapse
    whitespace, cap length.  We render as plain text in the card."""
    note = re.sub(r"</?[a-zA-Z][^>]*>", "", note)         # HTML tags
    note = re.sub(r"\*\*(.+?)\*\*", r"\1", note)          # **bold**
    note = re.sub(r"\*(.+?)\*", r"\1", note)              # *italic*
    note = re.sub(r"^\s*[-*•]\s+", "", note, flags=re.M)  # bullets
    note = re.sub(r"^\s*\d+\.\s+", "", note, flags=re.M)  # numbered lists
    note = re.sub(r"\s+", " ", note).strip()
    if len(note) > 400:
        note = note[:397].rstrip() + "..."
    return note


def generate_usage_notes(
    entries: list[dict],
    cache_dir: Path,
    model: str,
    host: str,
    prompt_version: str = USAGE_NOTE_PROMPT_VERSION,
    timeout: float = 60.0,
    temperature: float = 0.3,
    max_tokens: int = 120,
    use_cache: bool = True,
    progress: Optional[Callable[[int, int, str], None]] = None,
) -> list[tuple[str, str, str]]:
    """Populate entry['usage_note'] for every entry.

    Returns a list of failures as (rank, word, reason).  Failures are
    non-fatal: the entry's usage_note is left empty and generation
    continues with the next entry.
    """
    failures: list[tuple[str, str, str]] = []
    cache_hits = 0
    cache_misses = 0
    cache_dir.mkdir(parents=True, exist_ok=True)

    total = len(entries)
    for index, entry in enumerate(entries, start=1):
        word = entry["word"]
        translation = entry["translation"]

        if progress:
            progress(index, total, word)

        key = llm_cache_key_for(model, prompt_version, word, translation)
        cache_path = cache_dir / f"{slugify(word)}_{key}.json"

        if use_cache and cache_path.exists() and cache_path.stat().st_size > 0:
            try:
                with open(cache_path, "r", encoding="utf-8") as f:
                    cached = json.load(f)
                entry["usage_note"] = cached.get("note", "")
                cache_hits += 1
                continue
            except (json.JSONDecodeError, OSError):
                # Corrupt cache entry -> fall through and regenerate.
                pass

        # Build the prompt.  We strip tags from example_ru so we don't send
        # the model "<b>...</b>" markup.
        example_ru = strip_tags(entry.get("example_ru", "")).strip()
        user_prompt = USAGE_NOTE_USER_TEMPLATE.format(
            word=word,
            translation=translation,
            example_ru=example_ru or "(none)",
        )

        try:
            raw = _call_ollama(
                host=host, model=model,
                system=USAGE_NOTE_SYSTEM, user=user_prompt,
                timeout=timeout, temperature=temperature, max_tokens=max_tokens,
            )
            note = _sanitize_usage_note(raw)
            entry["usage_note"] = note
            cache_misses += 1

            with open(cache_path, "w", encoding="utf-8") as f:
                json.dump(
                    {
                        "note": note,
                        "model": model,
                        "prompt_version": prompt_version,
                        "word": word,
                        "translation": translation,
                        "raw": raw,
                    },
                    f, ensure_ascii=False, indent=2,
                )
        except LLMError as exc:
            entry["usage_note"] = ""
            failures.append((entry["rank"], word, str(exc)))

    print(f"  LLM cache: {cache_hits} reused, {cache_misses} generated")
    return failures


def write_llm_failed_log(path: Path, failures: list[tuple[str, str, str]]) -> None:
    with open(path, "w", encoding="utf-8") as f:
        for rank, word, reason in failures:
            f.write(f"#{rank} {word} ({reason})\n")



