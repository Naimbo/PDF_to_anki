#!/usr/bin/env python3
"""Convert a Russian frequency-list PDF into an Anki deck with TTS audio
and optional LLM-generated usage notes.

Expected PDF layout:

    1 - И [i] - And
    Вчера она купила фрукты и овощи.
    She bought some fruit and vegetables yesterday.

Audio is generated online with Microsoft Edge TTS using the Russian male
voice ``ru-RU-DmitryNeural`` by default.  Each note produces two Anki cards:
Russian -> English and English -> Russian, and each includes both a
normal-speed and a slowed-down clip of the Russian example sentence.

Optional usage notes are generated by a locally-running Ollama model
(default: llama3.1:8b).  Notes are opt-in via --llm ollama and are cached
under --llm-cache-dir just like TTS audio.

Install:
    python3 -m pip install pdfplumber genanki edge-tts

Optional, for --llm ollama:
    - Install Ollama:   https://ollama.com/download
    - Pull a model:     ollama pull llama3.1:8b
    - Start the server: ollama serve

Self-tests (no PDF, no network, no Ollama required):
    python3 pdf_to_anki_edge.py --self-test
"""

