def main() -> None:
    args = parse_args()

    if args.self_test:
        sys.exit(_run_self_tests())

    if args.preview:
        raw_entries = [dict(entry) for entry in PREVIEW_ENTRIES]
        if args.deck_name == "Russian Most Frequent Words":
            args.deck_name = "Russian Frequency - 5 Word Preview"
        print("Using the built-in five-word preview.")
    else:
        if not Path(args.pdf).exists():
            raise ConversionError(f"File not found: {args.pdf}")
        print(f"Reading {args.pdf} ...")
        raw_entries = parse_entries(extract_text(args.pdf), debug=args.debug_parse)

    entries = clean_entries(raw_entries)
    if not entries:
        raise ParsingError("No entries were found. Check the PDF text layout.")
    total_entries = len(entries)
    print(f"PDF entries found: {total_entries}")

    rank_mismatches = assign_sequence(entries)
    if rank_mismatches:
        print(
            "Warning: printed rank number didn't match actual position in the PDF "
            "for these entries (--start/--end still use the PRINTED rank; a gap "
            "here means one of these numbers may not select what you expect): "
            + ", ".join(rank_mismatches[:20]),
            file=sys.stderr,
        )

    requested_lo = requested_hi = None
    if args.start is not None or args.end is not None:
        entries, requested_lo, requested_hi = select_by_rank_range(entries, args.start, args.end)
        if not entries:
            raise ParsingError("No entries fall within the requested --start/--end range.")
        if args.deck_name == "Russian Most Frequent Words":
            lo = min(e["rank_int"] for e in entries)
            hi = max(e["rank_int"] for e in entries)
            args.deck_name = f"Russian Most Frequent Words ({lo}-{hi})"
    elif args.first is not None:
        entries = entries[: args.first]
        print(f"Using {len(entries)} of {total_entries} entries ({len(entries) * 2} cards).")
    else:
        print(f"Selected entries: all {total_entries} ({total_entries * 2} cards).")

    entries.sort(key=lambda e: e["seq"])  # export order == frequency order

    missing_examples = [
        entry["rank"] for entry in entries if not entry["example_ru"] or not entry["example_en"]
    ]
    if missing_examples:
        print("Warning: entries missing an example: "
              + ", ".join(missing_examples[:20]), file=sys.stderr)

    mixed_language = find_mixed_language_entries(entries)
    if mixed_language:
        print(
            "Warning: these entries' examples still look like they're in the wrong "
            "language after parsing (likely leftover dictionary/footnote text) - "
            "worth checking manually: " + ", ".join(mixed_language[:20]),
            file=sys.stderr,
        )

    unbolded = find_unbolded_entries(entries)
    if unbolded:
        print(
            "Warning: target word not found verbatim in its example sentence "
            "(likely an inflected form) - not bolded on these cards: "
            + ", ".join(unbolded[:20]),
            file=sys.stderr,
        )

    # --- Dry run: stop before any TTS / LLM work -----------------------------
    if args.dry_run:
        print()
        print("Dry run - no audio or files were generated")
        print("-------------------------------------------")
        if requested_lo is not None:
            print(f"Requested range: {requested_lo}-{requested_hi}")
        elif args.first is not None:
            print(f"Requested: first {args.first} (via --first)")
        else:
            print("Requested range: (all)")
        print(f"Selected entries: {len(entries)}")
        print()
        print(f"Missing examples: {len(missing_examples)}")
        print(f"Mixed-language examples: {len(mixed_language)}")
        print(f"Rank mismatches: {len(rank_mismatches)}")
        print(f"Unbolded target words: {len(unbolded)}")
        print()
        print(f"Cards to create: {len(entries) * 2}")
        if args.llm == "ollama":
            print(f"LLM backend requested: ollama ({args.llm_model} @ {args.llm_host})")
        else:
            print("LLM backend: none (no usage notes will be generated)")
        return

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # --- Audio stage ---------------------------------------------------------
    media_files: list[str] = []
    failures: list[tuple[str, str, str]] = []
    if args.no_audio:
        for entry in entries:
            entry["audio_tag"] = ""
            entry["example_audio_tag"] = ""
            entry["example_audio_slow_tag"] = ""
        print("Audio generation skipped (--no-audio).")
    else:
        engine = pick_tts_engine(args.tts_engine)
        check_audio_dependencies(engine)
        voice = resolve_voice(engine, args.voice)
        normal_rate, slow_rate = resolve_speeds(args, engine)
        print(f"Generating audio with {engine}, voice {voice} "
              f"(normal={normal_rate!r}, slow={slow_rate!r}) ...")

        def audio_progress(i: int, n: int, word: str) -> None:
            print(f"  Audio {i}/{n}: {word}")

        media_files, failures = add_audio_to_entries(
            entries, Path(args.cache_dir), engine=engine, voice=voice,
            normal_rate=normal_rate, slow_rate=slow_rate,
            edge_pitch=args.edge_pitch, rhvoice_pitch=args.rhvoice_pitch,
            mp3_bitrate=args.mp3_bitrate,
            edge_retries=args.edge_retries, edge_retry_delay=args.edge_retry_delay,
            use_cache=not args.no_cache,
            progress=audio_progress,
        )

        n_word = sum(1 for e in entries if e.get("audio_tag"))
        n_sentence = sum(1 for e in entries if e.get("example_audio_tag"))
        n_slow = sum(1 for e in entries if e.get("example_audio_slow_tag"))
        total = len(entries)
        print()
        print("Audio generation")
        print("-----------------")
        print(f"Word audio:           {n_word}/{total}")
        print(f"Example audio:        {n_sentence}/{total}")
        print(f"Slow example audio:   {n_slow}/{total}")
        if failures:
            print()
            print("Failed audio:")
            for rank, word, clip_type in failures[:30]:
                print(f"  #{rank} {word} ({clip_type})")
            if len(failures) > 30:
                print(f"  ... and {len(failures) - 30} more (see the failed-audio log)")
            failed_log_path = Path(args.failed_log) if args.failed_log else (
                output_path.with_name(output_path.stem + ".failed.txt")
            )
            write_failed_log(failed_log_path, failures)
            print(f"Full list written to {failed_log_path}")

    # --- LLM stage -----------------------------------------------------------
    llm_failures: list[tuple[str, str, str]] = []
    if args.llm == "ollama":
        print()
        print(f"Generating usage notes with {args.llm_model} via Ollama at {args.llm_host} ...")
        check_ollama_available(args.llm_host, args.llm_model)

        def llm_progress(i: int, n: int, word: str) -> None:
            print(f"  Note {i}/{n}: {word}")

        llm_failures = generate_usage_notes(
            entries,
            cache_dir=Path(args.llm_cache_dir),
            model=args.llm_model,
            host=args.llm_host,
            prompt_version=args.llm_prompt_version,
            timeout=args.llm_timeout,
            temperature=args.llm_temperature,
            max_tokens=args.llm_max_tokens,
            use_cache=not args.no_llm_cache,
            progress=llm_progress,
        )

        n_notes = sum(1 for e in entries if e.get("usage_note"))
        total = len(entries)
        print()
        print("Usage notes")
        print("-----------")
        print(f"Notes generated:      {n_notes}/{total}")
        print(f"Notes failed:         {len(llm_failures)}")
        if llm_failures:
            print()
            print("Failed notes (first 30):")
            for rank, word, reason in llm_failures[:30]:
                # Trim long reason strings for the terminal summary.
                reason_short = reason.splitlines()[0] if reason else "(no reason)"
                print(f"  #{rank} {word} ({reason_short[:70]})")
            if len(llm_failures) > 30:
                print(f"  ... and {len(llm_failures) - 30} more (see the failed-notes log)")
            llm_failed_log_path = Path(args.llm_failed_log) if args.llm_failed_log else (
                output_path.with_name(output_path.stem + ".llm_failed.txt")
            )
            write_llm_failed_log(llm_failed_log_path, llm_failures)
            print(f"Full list written to {llm_failed_log_path}")
    else:
        # Explicitly blank so the field exists on every entry and the CSV
        # column is populated (with empty strings).
        for entry in entries:
            entry.setdefault("usage_note", "")

    # --- Build and write -----------------------------------------------------
    deck = build_deck(entries, args.deck_name)
    genanki.Package(deck, media_files=media_files).write_to_file(str(output_path))

    print(f"\nWrote {args.output}")
    if args.csv:
        write_csv(entries, args.csv)
        print(f"Wrote {args.csv}")


# --- Self-tests --------------------------------------------------------------

def _run_self_tests() -> int:
    """Minimal built-in test suite. Returns process exit code.

    Covers the parsing heuristics and cache-key stability.  No PDF, no
    network, no ffmpeg, no Ollama required.
    """
    tests: list[tuple[str, Callable[[], None]]] = []

    def case(name: str):
        def deco(fn):
            tests.append((name, fn))
            return fn
        return deco

    @case("classify_word: russian")
    def _():
        assert classify_word("привет") == "ru"

    @case("classify_word: english")
    def _():
        assert classify_word("hello") == "en"

    @case("classify_word: neutral punctuation")
    def _():
        assert classify_word("...") == "neutral"
        assert classify_word("123") == "neutral"

    @case("split_bilingual: long merged line")
    def _():
        ru, en = split_bilingual_line(
            "Я могу зайти завтра, если хочешь.    I can drop by tomorrow if you want."
        )
        assert ru == "Я могу зайти завтра, если хочешь."
        assert en == "I can drop by tomorrow if you want."

    @case("split_bilingual: short both-terminal")
    def _():
        ru, en = split_bilingual_line("Да.   Yes.")
        assert ru == "Да."
        assert en == "Yes."

    @case("split_bilingual: single-language line returns None")
    def _():
        ru, en = split_bilingual_line("Вчера она купила фрукты и овощи.")
        assert ru is None and en is None

    @case("bold_word_in_sentence: exact match")
    def _():
        out = bold_word_in_sentence("Книга лежит на столе.", "на")
        assert "<b>на</b>" in out

    @case("bold_word_in_sentence: HTML-safe")
    def _():
        out = bold_word_in_sentence("a < b & c > d", "b")
        # The b word should not appear raw; the sentence should be escaped.
        assert "&lt;" in out and "&amp;" in out

    @case("bold_word_in_sentence: inflected form not bolded")
    def _():
        out = bold_word_in_sentence("Он поднял руку.", "рука")
        assert "<b>" not in out

    @case("strip_tags: removes b tags")
    def _():
        assert strip_tags("a <b>b</b> c") == "a b c"

    @case("strip_tags: handles stray angle brackets")
    def _():
        # Should not raise, and should not lose the trailing text.
        out = strip_tags("x < y > z")
        assert "x" in out and "z" in out

    @case("cache_key_for: changes when text changes")
    def _():
        a = cache_key_for("edge", "v", "+0%", "+0Hz", "hello")
        b = cache_key_for("edge", "v", "+0%", "+0Hz", "world")
        assert a != b

    @case("cache_key_for: stable for same input")
    def _():
        a = cache_key_for("edge", "v", "+0%", "+0Hz", "hello")
        b = cache_key_for("edge", "v", "+0%", "+0Hz", "hello")
        assert a == b

    @case("cache_key_for: changes when voice changes")
    def _():
        a = cache_key_for("edge", "v1", "+0%", "+0Hz", "hello")
        b = cache_key_for("edge", "v2", "+0%", "+0Hz", "hello")
        assert a != b

    @case("llm_cache_key_for: prompt version bumps key")
    def _():
        a = llm_cache_key_for("m", "1", "и", "and")
        b = llm_cache_key_for("m", "2", "и", "and")
        assert a != b

    @case("llm_cache_key_for: ignores example sentence")
    def _():
        # Same (model, prompt_version, word, translation) -> same key,
        # regardless of anything else.
        a = llm_cache_key_for("m", "1", "и", "and")
        b = llm_cache_key_for("m", "1", "и", "and")
        assert a == b

    @case("_sanitize_usage_note: strips bold markdown")
    def _():
        out = _sanitize_usage_note("This is **bold** text.")
        assert "**" not in out
        assert "bold" in out

    @case("_sanitize_usage_note: strips bullet prefix")
    def _():
        out = _sanitize_usage_note("- first point\n- second point")
        assert not out.startswith("-")
        assert "first point" in out

    @case("_sanitize_usage_note: caps length")
    def _():
        out = _sanitize_usage_note("word " * 500)
        assert len(out) <= 400
        assert out.endswith("...")

    @case("_sanitize_usage_note: collapses whitespace")
    def _():
        out = _sanitize_usage_note("a    b\n\nc")
        assert out == "a b c"

    @case("resolve_speeds: edge --speed override produces rate string")
    def _():
        # Fake a minimal namespace.
        class NS:
            speed = 75
            slow_speed = None
            edge_rate = "+0%"
            slow_rate = "-50%"
            rhvoice_rate = 100
            tts_speed = 140
        normal, slow = resolve_speeds(NS(), "edge")
        assert normal == "-25%"
        assert slow == "-50%"

    @case("resolve_speeds: espeak slow never faster than normal")
    def _():
        class NS:
            speed = None
            slow_speed = None
            edge_rate = "+0%"
            slow_rate = "-50%"
            rhvoice_rate = 100
            tts_speed = 30   # pathologically slow
        normal, slow = resolve_speeds(NS(), "espeak")
        assert slow < normal

    failed = 0
    for name, fn in tests:
        try:
            fn()
            print(f"PASS  {name}")
        except AssertionError as exc:
            failed += 1
            print(f"FAIL  {name}: {exc}")
        except Exception as exc:  # noqa: BLE001
            failed += 1
            print(f"ERROR {name}: {type(exc).__name__}: {exc}")

    total = len(tests)
    print()
    print(f"{total - failed}/{total} tests passed")
    return 1 if failed else 0


